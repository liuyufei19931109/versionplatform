package com.local.release.service;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.test.system.CapturedOutput;
import org.springframework.boot.test.system.OutputCaptureExtension;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.core.env.MapPropertySource;
import javax.sql.DataSource;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.nio.file.attribute.PosixFilePermissions;
import java.sql.*;
import java.util.*;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.zip.ZipInputStream;
import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

@ExtendWith(OutputCaptureExtension.class)
class H2ShutdownBackupTest {
  @TempDir Path temporary;

  @Test void springShutdownBacksUpCommittedFileDatabaseAndKeysBeforeClosingThePool() throws Exception {
    Path root = temporary.resolve("private backup's"), keys = temporary.resolve("keys");
    Files.createDirectories(keys);
    Path credential = keys.resolve("credential-encryption.key"), totp = keys.resolve("totp-encryption.key");
    // Deliberately public test material, never application credentials.
    Files.writeString(credential, "test-credential-key-only\n"); Files.writeString(totp, "test-totp-key-only\n");
    byte[] credentialBefore = Files.readAllBytes(credential), totpBefore = Files.readAllBytes(totp);
    AtomicBoolean snapshotExistsBeforePoolClose = new AtomicBoolean();
    HikariDataSource pool = new HikariDataSource(configuration(fileUrl("application"))) {
      @Override public void close() {
        snapshotExistsBeforePoolClose.set(completedDirectories(root).size() == 1 && !isClosed());
        super.close();
      }
    };
    AnnotationConfigApplicationContext context = new AnnotationConfigApplicationContext();
    try {
      context.getEnvironment().getPropertySources().addFirst(new MapPropertySource("backup-test", Map.of(
        "release.shutdown-backup-dir", root.toString(), "release.credential-key-file", credential.toString(), "release.totp-key-file", totp.toString())));
      context.registerBean("dataSource", HikariDataSource.class, () -> pool);
      context.register(H2ShutdownBackup.class);
      context.refresh();
      try (Connection connection = pool.getConnection(); Statement statement = connection.createStatement()) {
        assertThat(connection.getMetaData().getDatabaseProductVersion()).startsWith("2.5.250");
        statement.execute("CREATE TABLE RELEASE_RECORD (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NOTE CLOB)");
        statement.execute("CREATE SEQUENCE BUILD_NUMBER START WITH 63");
        try (PreparedStatement insert = connection.prepareStatement("INSERT INTO RELEASE_RECORD (NOTE) VALUES (?)")) {
          for (int i = 0; i < 60; i++) { insert.setString(1, "发布记录-" + i + ":" + "known-test-body".repeat(600)); insert.executeUpdate(); }
        }
        try (ResultSet result = statement.executeQuery("SELECT NEXT VALUE FOR BUILD_NUMBER")) { result.next(); assertThat(result.getLong(1)).isEqualTo(63); }
      }
      context.close();
      assertThat(snapshotExistsBeforePoolClose).isTrue();
      assertThat(pool.isClosed()).isTrue();
      Path backup = onlyCompleted(root);
      assertThat(Files.readAllBytes(backup.resolve("credential-encryption.key"))).isEqualTo(credentialBefore);
      assertThat(Files.readAllBytes(backup.resolve("totp-encryption.key"))).isEqualTo(totpBefore);
      assertThat(Files.readAllBytes(credential)).isEqualTo(credentialBefore);
      assertThat(Files.readAllBytes(totp)).isEqualTo(totpBefore);
      assertThat(backup.resolve("database.zip.incomplete")).doesNotExist();
      verifyPrivatePermissions(root, backup);
      Path restored = restore(backup.resolve("database.zip"));
      try (Connection connection = DriverManager.getConnection("jdbc:h2:file:" + restored + ";IFEXISTS=TRUE", "sa", ""); Statement statement = connection.createStatement()) {
        try (ResultSet rows = statement.executeQuery("SELECT COUNT(*), MAX(ID) FROM RELEASE_RECORD")) { rows.next(); assertThat(rows.getInt(1)).isEqualTo(60); assertThat(rows.getInt(2)).isEqualTo(60); }
        try (ResultSet row = statement.executeQuery("SELECT NOTE FROM RELEASE_RECORD WHERE ID=60")) { row.next(); assertThat(row.getString(1)).isEqualTo("发布记录-59:" + "known-test-body".repeat(600)); }
        try (ResultSet result = statement.executeQuery("SELECT NEXT VALUE FOR BUILD_NUMBER")) { result.next(); assertThat(result.getLong(1)).isGreaterThan(63); /* A backed-up sequence cache may skip unused values, but must never reuse an issued ID. */ }
      }
    } finally { context.close(); if (!pool.isClosed()) pool.close(); }
  }

  @Test void snapshotExcludesUncommittedWorkAndDoesNotCommitAnotherConnection() throws Exception {
    Path root = temporary.resolve("backups");
    try (HikariDataSource pool = new HikariDataSource(configuration(fileUrl("transactions"))); Connection writer = pool.getConnection()) {
      try (Statement statement = writer.createStatement()) { statement.execute("CREATE TABLE HISTORY (ID INT PRIMARY KEY)"); statement.execute("INSERT INTO HISTORY VALUES (1)"); }
      writer.setAutoCommit(false);
      try (Statement statement = writer.createStatement()) { statement.executeUpdate("INSERT INTO HISTORY VALUES (2)"); }
      backup(pool, root).backupBeforeShutdown();
      writer.rollback();
      Path restored = restore(onlyCompleted(root).resolve("database.zip"));
      try (Connection reader = DriverManager.getConnection("jdbc:h2:file:" + restored + ";IFEXISTS=TRUE", "sa", ""); Statement statement = reader.createStatement(); ResultSet rows = statement.executeQuery("SELECT ID FROM HISTORY ORDER BY ID")) {
        assertThat(rows.next()).isTrue(); assertThat(rows.getInt(1)).isEqualTo(1); assertThat(rows.next()).isFalse();
      }
    }
  }

  @Test void eachShutdownUsesAUniqueDirectoryAndNeverCreatesMissingKeys() throws Exception {
    Path root = temporary.resolve("backups");
    try (HikariDataSource pool = new HikariDataSource(configuration(fileUrl("unique")))) {
      H2ShutdownBackup first = backup(pool, root);
      first.backupBeforeShutdown(); first.backupBeforeShutdown();
      assertThat(completedDirectories(root)).hasSize(1);
      backup(pool, root).backupBeforeShutdown();
      assertThat(completedDirectories(root)).hasSize(2);
      assertThat(temporary.resolve("missing-credential.key")).doesNotExist();
      assertThat(temporary.resolve("missing-totp.key")).doesNotExist();
      for (Path directory : completedDirectories(root)) {
        assertThat(directory.resolve("credential-encryption.key")).doesNotExist();
        assertThat(directory.resolve("totp-encryption.key")).doesNotExist();
      }
    }
  }

  @Test void memoryH2AndMysqlAreSkippedWithoutCreatingBackupFiles() throws Exception {
    Path memoryRoot = temporary.resolve("memory-backups"), mysqlRoot = temporary.resolve("mysql-backups");
    try (HikariDataSource pool = new HikariDataSource(configuration("jdbc:h2:mem:backup-skip-test"))) {
      backup(pool, memoryRoot).backupBeforeShutdown();
      assertThat(memoryRoot).doesNotExist();
    }
    DataSource mysql = mock(DataSource.class); Connection connection = mock(Connection.class); DatabaseMetaData metadata = mock(DatabaseMetaData.class);
    when(mysql.getConnection()).thenReturn(connection); when(connection.getMetaData()).thenReturn(metadata);
    when(metadata.getURL()).thenReturn("jdbc:mysql://localhost/test"); when(metadata.getDatabaseProductName()).thenReturn("MySQL");
    backup(mysql, mysqlRoot).backupBeforeShutdown();
    verify(connection, never()).prepareStatement(anyString()); verify(connection).close();
    assertThat(mysqlRoot).doesNotExist();
  }

  @Test void failedBackupIsExplicitWithoutLoggingSqlOrCredentials(CapturedOutput output) throws Exception {
    DataSource broken = mock(DataSource.class);
    when(broken.getConnection()).thenThrow(new SQLException("SELECT secret FROM private_data password=should-never-be-logged"));
    assertThatCode(() -> backup(broken, temporary.resolve("backup-root")).backupBeforeShutdown()).doesNotThrowAnyException();
    assertThat(output.getAll()).contains("H2_SHUTDOWN_BACKUP status=FAILED").doesNotContain("SELECT secret", "private_data", "should-never-be-logged");
    assertThat(temporary.resolve("backup-root")).doesNotExist();
  }

  @Test void incompleteKeyCopyNeverGetsACompleteMarker(CapturedOutput output) throws Exception {
    Path root = temporary.resolve("backups"), badKey = temporary.resolve("key-is-directory"); Files.createDirectory(badKey);
    try (HikariDataSource pool = new HikariDataSource(configuration(fileUrl("key-copy-failure")))) {
      H2ShutdownBackup hook = new H2ShutdownBackup(pool, root.toString(), badKey.toString(), temporary.resolve("absent.key").toString());
      hook.backupBeforeShutdown();
      assertThat(completedDirectories(root)).isEmpty();
      try (var paths = Files.list(root)) {
        Path incomplete = paths.findFirst().orElseThrow();
        assertThat(incomplete.resolve("database.zip.incomplete")).isRegularFile();
        assertThat(incomplete.resolve("database.zip")).doesNotExist();
        assertThat(incomplete.resolve("COMPLETE")).doesNotExist();
      }
      assertThat(output.getAll()).contains("H2_SHUTDOWN_BACKUP status=FAILED");
    }
  }

  private H2ShutdownBackup backup(DataSource source, Path root) {
    return new H2ShutdownBackup(source, root.toString(), temporary.resolve("missing-credential.key").toString(), temporary.resolve("missing-totp.key").toString());
  }
  private String fileUrl(String name) { return "jdbc:h2:file:" + temporary.resolve(name) + ";DB_CLOSE_ON_EXIT=FALSE"; }
  private static HikariConfig configuration(String url) {
    HikariConfig config = new HikariConfig(); config.setJdbcUrl(url); config.setUsername("sa"); config.setPassword("");
    config.setMaximumPoolSize(3); config.setMinimumIdle(1); config.setConnectionTimeout(5000); return config;
  }
  private static List<Path> completedDirectories(Path root) {
    if (!Files.isDirectory(root)) return List.of();
    try (var paths = Files.list(root)) { return paths.filter(path -> Files.isRegularFile(path.resolve("COMPLETE"))).toList(); }
    catch (IOException error) { throw new AssertionError(error); }
  }
  private static Path onlyCompleted(Path root) { List<Path> values = completedDirectories(root); assertThat(values).hasSize(1); return values.getFirst(); }
  private Path restore(Path archive) throws IOException {
    Path directory = Files.createTempDirectory(temporary, "restored-");
    try (ZipInputStream zip = new ZipInputStream(Files.newInputStream(archive))) {
      for (var entry = zip.getNextEntry(); entry != null; entry = zip.getNextEntry()) {
        Path target = directory.resolve(entry.getName()).normalize();
        if (!target.startsWith(directory)) throw new IOException("Unexpected archive path");
        if (entry.isDirectory()) Files.createDirectories(target);
        else { Files.createDirectories(target.getParent()); Files.copy(zip, target); }
      }
    }
    try (var paths = Files.walk(directory)) {
      List<Path> databases = paths.filter(path -> path.toString().endsWith(".mv.db")).toList(); assertThat(databases).hasSize(1);
      String filename = databases.getFirst().toString(); return Path.of(filename.substring(0, filename.length() - ".mv.db".length()));
    }
  }
  private static void verifyPrivatePermissions(Path root, Path directory) throws IOException {
    if (!root.getFileSystem().supportedFileAttributeViews().contains("posix")) return;
    assertThat(Files.getPosixFilePermissions(root)).isEqualTo(PosixFilePermissions.fromString("rwx------"));
    assertThat(Files.getPosixFilePermissions(directory)).isEqualTo(PosixFilePermissions.fromString("rwx------"));
    try (var files = Files.list(directory)) { for (Path file : files.toList()) assertThat(Files.getPosixFilePermissions(file)).isEqualTo(PosixFilePermissions.fromString("rw-------")); }
  }
}